const supportedLanguages =['en', 'fr', 'de', 'nl', 'pt', 'it', 'id', 'hi', 'ja', 'ko', 'zh', 'es', 'ru', 'ar'];

window.i18n = {
    lang: 'en',
    
    init() {
        const browserLang = (navigator.language || navigator.userLanguage).slice(0, 2).toLowerCase();
        this.lang = supportedLanguages.includes(browserLang) ? browserLang : 'en';

        // Map non-English supported languages to the English dictionary for structural placeholder purposes
        if (!translations[this.lang] || Object.keys(translations[this.lang]).length === 0) {
            translations[this.lang] = translations['en']; 
        }

        this.translateDOM();
    },

    t(key, vars = {}) {
        let text = translations[this.lang][key] || translations['en'][key] || key;
        
        // Handle variable injection {{dynamic_vars}}
        for (const [varName, value] of Object.entries(vars)) {
            const regex = new RegExp(`{{\\s*${varName}\\s*}}`, 'g');
            text = text.replace(regex, value);
        }
        
        return text;
    },

    translateDOM() {
        // Standard text replacements
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            el.innerText = this.t(key);
        });

        // Inner HTML replacements (used for strings with strong/span tags)
        document.querySelectorAll('[data-i18n-html]').forEach(el => {
            const key = el.getAttribute('data-i18n-html');
            const dynamicVarMap = {};
            
            // Extract any data-i18n-var-* attributes to pass into the translation engine
            Array.from(el.attributes).forEach(attr => {
                if (attr.name.startsWith('data-i18n-var-')) {
                    const varName = attr.name.replace('data-i18n-var-', '');
                    dynamicVarMap[varName] = attr.value;
                }
            });
            
            el.innerHTML = this.t(key, dynamicVarMap);
        });

        // Placeholders
        document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
            const key = el.getAttribute('data-i18n-placeholder');
            el.setAttribute('placeholder', this.t(key));
        });
    }
};